const { readFileSync } = require("node:fs")
const { test } = require("node:test")
const assert = require("node:assert/strict")
const path = require("node:path")

const source = readFileSync(path.join(__dirname, "page.tsx"), "utf8")

test("landing page keeps the focused Saathi entry hierarchy", () => {
  assert.match(source, /Move work forward\./)
  assert.match(source, /A focused workspace for teams that build together\./)
  assert.match(source, /Turn ideas into/)
  assert.match(source, /real progress/)
  assert.match(source, /with <span className=\"text-primary\">Saathi\./)
  assert.match(source, /href="\/login"/)
  assert.match(source, /href="\/register"/)
  assert.match(source, /saathi-hero-texture/)
  assert.match(source, /Plan with clarity/)
  assert.match(source, /Work together/)
  assert.match(source, /Stay on track/)
  assert.doesNotMatch(source, /Command center|Live engine|SSE task updates/)
})
